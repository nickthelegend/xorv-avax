// Writes packages/sdk/src/abi.ts from the Foundry build (contracts/out). Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'contracts/out');
const pick = {
  testDollarAbi: 'TestDollar.sol/TestDollar.json',
  xorvIndexAbi: 'XorvIndex.sol/XorvIndex.json',
  xorvRegistryAbi: 'XorvRegistry.sol/XorvRegistry.json',
  xorvMarketAbi: 'XorvMarket.sol/XorvMarket.json',
  x402RouterAbi: 'X402Router.sol/X402Router.json',
  xorvForwardAbi: 'XorvForward.sol/XorvForward.json',
  encryptedErcAbi: 'EncryptedERC.sol/EncryptedERC.json',
  registrarAbi: 'Registrar.sol/Registrar.json',
};
let ts = '// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n';
for (const [name, file] of Object.entries(pick)) {
  const abi = JSON.parse(readFileSync(path.join(out, file), 'utf8')).abi;
  ts += `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(path.join(root, 'packages/sdk/src/abi.ts'), ts);
console.log(`wrote packages/sdk/src/abi.ts (${Object.keys(pick).length} ABIs)`);
